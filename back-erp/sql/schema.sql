-- Esquema independiente: no borra ni modifica las tablas del proyecto anterior.
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('ADMIN','CAJERO') NOT NULL DEFAULT 'CAJERO', active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS products (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, price_cents INT NOT NULL,
 stock INT NOT NULL DEFAULT 0, reserved INT NOT NULL DEFAULT 0, minimum INT NOT NULL DEFAULT 5, active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS suppliers (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL, phone VARCHAR(20) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS purchases (
 id INT AUTO_INCREMENT PRIMARY KEY, supplier_id INT NOT NULL, total_cents INT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (supplier_id) REFERENCES suppliers(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS purchase_items (
 purchase_id INT NOT NULL, product_id INT NOT NULL, quantity INT NOT NULL, cost_cents INT NOT NULL,
 PRIMARY KEY(purchase_id, product_id), FOREIGN KEY(purchase_id) REFERENCES purchases(id), FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS employees (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, position VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL, salary_cents INT NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS payroll (
 id INT AUTO_INCREMENT PRIMARY KEY, employee_id INT NOT NULL, period CHAR(7) NOT NULL, amount_cents INT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY employee_period(employee_id,period), FOREIGN KEY(employee_id) REFERENCES employees(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sales (
 id CHAR(36) PRIMARY KEY, user_id INT NOT NULL, customer VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL,
 total_cents INT NOT NULL, status ENUM('CREANDO','CREADA','REVISION','PAGADA','CANCELADA') NOT NULL,
 method ENUM('EFECTIVO','PAYPAL') NOT NULL, paypal_id VARCHAR(100) UNIQUE, capture_id VARCHAR(100) UNIQUE,
 email_status ENUM('PENDIENTE','ENVIADA','ERROR') NOT NULL DEFAULT 'PENDIENTE', email_message_id VARCHAR(255),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sale_items (
 sale_id CHAR(36) NOT NULL, product_id INT NOT NULL, name VARCHAR(100) NOT NULL, quantity INT NOT NULL, price_cents INT NOT NULL,
 PRIMARY KEY(sale_id,product_id), FOREIGN KEY(sale_id) REFERENCES sales(id), FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS stock_movements (
 id INT AUTO_INCREMENT PRIMARY KEY, product_id INT NOT NULL, quantity INT NOT NULL, reason VARCHAR(150) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ledger (
 id INT AUTO_INCREMENT PRIMARY KEY, kind ENUM('INGRESO','EGRESO') NOT NULL, concept VARCHAR(150) NOT NULL,
 amount_cents INT NOT NULL, reference VARCHAR(100) UNIQUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
